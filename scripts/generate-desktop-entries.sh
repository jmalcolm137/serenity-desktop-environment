#!/usr/bin/env bash
# Generate freedesktop .desktop entries for the SerenityOS applications from
# their .af files (Base/res/apps). The Taskbar's XDG menu reads them through
# $XDG_DATA_DIRS/applications; host application menus can see them too.
#
#   generate-desktop-entries.sh --output <data-dir> [--source <apps-dir>]
#
# <data-dir>/applications is replaced. The session generates into the SDE state
# directory; install-sde.sh generates into $prefix/share/applications.
set -euo pipefail

SDE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LIBGUI_WAYLAND_ROOT="${LIBGUI_WAYLAND_ROOT:-$SDE_ROOT/../libgui-wayland}"
SERENITY="${SERENITY:-$LIBGUI_WAYLAND_ROOT/serenity}"
SOURCE="${SERENITY}/Base/res/apps"
OUTPUT=""

usage() {
    cat <<EOF
Usage: $0 --output <data-dir> [--source <apps-dir>]

  --output <dir>   data dir; entries are written to <dir>/applications
  --source <dir>   the SerenityOS apps dir (default: $SERENITY/Base/res/apps)
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --output) OUTPUT="${2:-}"; shift ;;
        --source) SOURCE="${2:-}"; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "unknown argument: $1" >&2; usage >&2; exit 2 ;;
    esac
    shift
done

if [[ -z "$OUTPUT" ]]; then
    usage >&2
    exit 2
fi
if [[ ! -d "$SOURCE" ]]; then
    echo "generate-desktop-entries: no apps dir at $SOURCE" >&2
    exit 0
fi

APPS_DIR="$OUTPUT/applications"
mkdir -p "$APPS_DIR"
rm -f "$APPS_DIR"/*.desktop

trim() {
    local value="$1"
    value="${value#"${value%%[![:space:]]*}"}"
    value="${value%"${value##*[![:space:]]}"}"
    printf '%s' "$value"
}

# Serenity's .af category (with & mnemonics, possibly a Games/Puzzles subpath) to
# the freedesktop main category.
xdg_category() {
    case "$1" in
        *Games*) printf 'Game;' ;;
        *Graphics*|*Demos*) printf 'Graphics;' ;;
        *Development*) printf 'Development;' ;;
        *Internet*) printf 'Network;' ;;
        *Media*) printf 'AudioVideo;' ;;
        *Office*) printf 'Office;' ;;
        Settings) printf 'Settings;' ;;
        *) printf 'Utility;' ;;
    esac
}

count=0
for af in "$SOURCE"/*.af; do
    [[ -e "$af" ]] || continue

    section=""
    name=""
    executable=""
    category=""
    arguments=""
    description=""
    icon_path=""
    terminal="false"
    exclude="false"

    while IFS= read -r line || [[ -n "$line" ]]; do
        line="${line%$'\r'}"
        case "$line" in
            \[*\]) section="${line:1:${#line}-2}"; continue ;;
        esac
        [[ "$section" == "App" ]] || continue
        key="$(trim "${line%%=*}")"
        value=""
        [[ "$line" == *=* ]] && value="$(trim "${line#*=}")"
        case "$key" in
            Name) name="$value" ;;
            Executable) executable="$value" ;;
            Category) category="$value" ;;
            Arguments) arguments="$value" ;;
            Description) description="$value" ;;
            IconPath) icon_path="$value" ;;
            RunInTerminal) terminal="$value" ;;
            ExcludeFromSystemMenu) exclude="$value" ;;
        esac
    done < "$af"

    [[ "$exclude" == "true" ]] && continue
    name="${name//&/}"
    [[ -n "$name" && -n "$executable" ]] || continue

    executable_name="$(basename "$executable")"
    [[ -n "$executable_name" ]] || continue
    desktop_id="$(basename "$af" .af)"

    # Keep the SerenityOS /bin/<name> form: the port resolves it to the session
    # app directory (a bare name would only be found on the host PATH).
    exec_line="$executable"
    [[ -n "$arguments" ]] && exec_line="$exec_line $arguments"
    [[ "$terminal" == "true" ]] || terminal="false"

    {
        echo "# Generated by sde-generate-desktop-entries; do not edit."
        echo "# Source: ${af##*/}"
        echo "[Desktop Entry]"
        echo "Type=Application"
        echo "Name=$name"
        if [[ -n "$description" ]]; then
            echo "Comment=$description"
        else
            echo "Comment=SerenityOS application"
        fi
        echo "Exec=$exec_line"
        echo "TryExec=$executable"
        if [[ -n "$icon_path" ]]; then
            echo "Icon=$icon_path"
        fi
        echo "Categories=$(xdg_category "$category")"
        echo "Terminal=$terminal"
        echo "OnlyShowIn=SDE;"
        echo "X-SerenityOS=true"
    } > "$APPS_DIR/$desktop_id.desktop"
    count=$((count + 1))
done

echo "generate-desktop-entries: wrote $count entries to $APPS_DIR"
